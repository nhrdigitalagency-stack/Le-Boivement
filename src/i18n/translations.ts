import { Language } from '../types/domain';

export function formatXaf(amount: number, lang: Language = 'fr'): string {
  const formatted = new Intl.NumberFormat(lang === 'fr' ? 'fr-CM' : 'en-CM', {
    maximumFractionDigits: 0,
  }).format(Math.round(amount || 0));
  return `${formatted} XAF`;
}

export function formatDateTime(iso: string, lang: Language = 'fr'): string {
  if (!iso) return '—';
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}

